import pyod.utils.data as pyod
import numpy as np
import matplotlib.pyplot as plt
X_train,_,Y_train,_= pyod.generate_data(n_train=1000, n_test=0, contamination=0.1,n_features=1)
print(X_train.shape)
med=float(input("Introduceti media(mean): "))
var=float(input("Introduceti varianta(standard deviation): "))
noise=np.random.normal(med,np.sqrt(var),(1000,1))
np.random.shuffle(X_train) 
x1,x2,x3,x4=np.split(X_train,4) 
x2=x2+np.random.normal(med,np.sqrt(var),x2.shape) 
x4=x4+np.random.normal(med,np.sqrt(var),x4.shape) 
a=float(input("Introduceti panta(a): ")) #citim panta
b=float(input("Introduceti ordonata la origine(b): "))
y1=a*x1+b+np.random.normal(med,np.sqrt(var),x1.shape)
y2=a*x2+b+np.random.normal(med,np.sqrt(var),x2.shape) 
y3=a*x3+b+np.random.normal(med,10*np.sqrt(var),x3.shape) 
y4=a*x4+b+np.random.normal(med,10*np.sqrt(var),x4.shape)
X=np.vstack((x1,x2,x3,x4)) 
y=np.vstack((y1,y2,y3,y4)) 
a=np.random.uniform(-10,10) 
b=np.random.uniform(-10,10)
Y_train=a*X_train+b+noise
H=Y_train@np.linalg.pinv(Y_train.T@Y_train)@Y_train.T
leverage_scores=np.diag(H)
print("Leverage scores: ",leverage_scores)
prag=np.quantile(leverage_scores,0.95) 
s1,s2,s3,s4=np.split(leverage_scores,4)
m1=s1>=prag 
m2=s2>=prag 
m3=s3>=prag 
m4=s4>=prag 
plt.figure(figsize=(10,10))
plt.subplot(2,2,1)
plt.scatter(x1,y1)
plt.scatter(x1[m1],y1[m1],c='r') 
plt.title("Puncte normale")
plt.subplot(2,2,2)
plt.scatter(x2,y2)
plt.scatter(x2[m2],y2[m2],c='r') 
plt.title("Puncte cu varianta pe X")
plt.subplot(2,2,3)
plt.scatter(x3,y3)
plt.scatter(x3[m3],y3[m3],c='r')
plt.title("Puncte cu varianta pe Y")
plt.subplot(2,2,4)
plt.scatter(x4,y4)
plt.scatter(x4[m4],y4[m4],c='r')
plt.title("Puncte cu varianta pe X si Y")
plt.show()
